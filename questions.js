// 유의어·반의어: 같은 유형이라도 문장 틀이 매번 같지 않게 형식을 고른다. 단어 → 뜻(1/2), 관계가 다른 쌍(1/4), 유의(반의) 관계인 쌍(1/4)
// 두 표에 모두 나오는 단어(절약·모방·실천·숙련 등)는 단어 문제에서 다른 표의 짝을 함정 오답으로 쓰고, 쌍 문제에서는 빼서 정답이 둘로 읽힐 여지를 없앤다
const BOTH = new Set(SYN.flat().filter(w => ANT.flat().includes(w)));
const plain = tbl => tbl.filter(p => !p.some(w => BOTH.has(w)));
const mate = (tbl, w) => tbl.find(p => p.includes(w))?.find(x => x !== w);
const lexQ = syn => {
  const [tbl, other, ask, mk, omk, name] = syn ? [SYN, ANT, '가장 비슷한', '≒', '↔', '유의'] : [ANT, SYN, '반대되는', '↔', '≒', '반의'];
  const f = pick([0, 0, 1, 2]);
  if (!f) {
    const i = R(0, tbl.length - 1), k = R(0, 1), w = tbl[i][k], a = tbl[i][1 - k], trap = mate(other, w); // 짝의 어느 쪽이든 문제 단어가 된다
    const wrongs = others(tbl, i, 1 - k).filter(x => x !== trap).slice(0, trap ? 3 : 4);
    return choiceQ('언어표현', `다음 단어와 뜻이 ${ask} 것은?<p><b>${w}</b></p>`, a, trap ? [trap, ...wrongs] : wrongs,
      `${w} ${mk} ${a}` + (trap ? ` (함정: ${w} ${omk} ${trap})` : ''));
  }
  // 정답 쌍 하나는 tbl에서, 나머지 넷은 other에서. 형식 2는 가끔 하나를 유의·반의가 아닌 쌍으로 바꾼다(상하 관계는 유의로 오해할 수 있어 뺀다)
  const opts = [[pick(plain(tbl)), mk], ...shuffle(plain(other)).slice(0, 4).map(p => [p, omk])];
  if (f === 2 && R(0, 1)) opts[4] = [pick(['직업과 일하는 곳', '원료와 제품', '양과 단위'].flatMap(n => REL[n])), '–'];
  const shown = opts.map(([p, m]) => [shuffle(p), m]), str = p => p.join(' – ');
  return choiceQ('언어표현', f === 1 ? '다음 중 두 단어의 관계가 나머지와 <u>다른</u> 것은?' : `다음 중 짝지어진 두 단어가 ${name} 관계인 것은?`,
    str(shown[0][0]), shown.slice(1).map(([p]) => str(p)),
    `${shown[0][0].join(` ${mk} `)}만 ${name} 관계이다. 나머지: ${shown.slice(1).map(([p, m]) => p.join(` ${m} `)).join(', ')} (≒ 유의, ↔ 반의)`);
};
